import { readFileSync, writeFileSync } from 'node:fs';
const p = 'src/ai/vortex/atlas/oracle-data.json';
const record = JSON.parse(readFileSync(p, 'utf8'));
writeFileSync('src/ai/vortex/atlas/oracle-data.js',
  `// Generated by tools/build-vortex-oracle.mjs. Do not edit by hand.\nexport default ${JSON.stringify(record)};\n`);
console.log('oracle-data.js written', record.lapTime, record.n);
