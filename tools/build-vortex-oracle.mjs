/**
 * Offline VORTEX oracle builder.
 *
 * Produces the fastest known nominal Harbor Ring trajectory from the canonical
 * vehicle envelope, then writes a deterministic atlas record that the runtime
 * TrackAtlas loads. The plant in src/sim is never modified.
 *
 *   node tools/build-vortex-oracle.mjs
 *   node tools/build-vortex-oracle.mjs --iterations 240 --no-write
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { Track } from '../src/sim/track.js';
import { RacingLine } from '../src/sim/ai.js';
import { SPEC } from '../src/sim/vehicle.js';
import { EnvelopeModel, referenceTyre } from '../src/ai/vortex/atlas/envelope.js';
import { TrackOracle } from '../src/ai/vortex/atlas/oracle.js';

const here = dirname(fileURLToPath(import.meta.url));
const argv = process.argv.slice(2);
const flag = name => argv.includes(name);
const number = (name, fallback) => {
  const i = argv.indexOf(name);
  return i >= 0 && Number.isFinite(Number(argv[i + 1])) ? Number(argv[i + 1]) : fallback;
};

const track = new Track('harbor-ring');
const line = new RacingLine(track, SPEC);

const envelope = new EnvelopeModel({
  classId: 'gt',
  fuel: 35,
  wing: 6,
  gripScale: number('--grip', 0.95),
  tyre: referenceTyre({ core: number('--core', 85) }),
});

const oracle = new TrackOracle(track, {
  envelope,
  spacing: number('--spacing', 2.2),
  qMax: number('--qmax', track.halfWidth - 0.99 - 0.12),
  qSlopeMax: number('--q-slope', Infinity),
});

// Warm start from the canonical elastic-band line so the optimiser begins from
// a feasible, already raceable geometry rather than from zero.
const initial = new Float64Array(oracle.n);
for (let i = 0; i < oracle.n; i++) initial[i] = line.offsetAt(oracle.s[i]);

const seed = oracle.evaluate(initial);
const start = Date.now();
const result = oracle.optimize({
  initial,
  iterations: number('--iterations', 120),
  step: number('--step', 1.4),
  smoothing: number('--smoothing', 12),
});
const elapsed = (Date.now() - start) / 1000;

const sampler = oracle.sampler(result);
const minSpeed = { v: Infinity, s: 0 };
const maxSpeed = { v: -Infinity, s: 0 };
const corners = [];
for (let i = 0; i < result.n; i++) {
  if (result.v[i] < minSpeed.v) { minSpeed.v = result.v[i]; minSpeed.s = oracle.s[i]; }
  if (result.v[i] > maxSpeed.v) { maxSpeed.v = result.v[i]; maxSpeed.s = oracle.s[i]; }
}
for (let i = 0; i < result.n; i++) {
  const k = Math.abs(result.kappa[i]);
  if (k < 0.02) continue;
  const prev = Math.abs(result.kappa[(i - 1 + result.n) % result.n]);
  if (k < prev) continue;
  const next = Math.abs(result.kappa[(i + 1) % result.n]);
  if (k < next) continue;
  corners.push({
    s: Number(oracle.s[i].toFixed(1)),
    radius: Number((1 / k).toFixed(2)),
    entrySpeed: Number(result.v[Math.max(0, i - 12)].toFixed(2)),
    apexSpeed: Number(result.v[i].toFixed(2)),
    exitSpeed: Number(result.v[Math.min(result.n - 1, i + 12)].toFixed(2)),
  });
}

const summary = {
  track: 'harbor-ring',
  trackLength: Number(track.length.toFixed(3)),
  legalOffset: Number(oracle.qMax.toFixed(3)),
  stations: result.n,
  spacing: Number(result.spacing.toFixed(3)),
  envelope: envelope.snapshot(40),
  prediction: {
    oracleLapTime: Number(result.time.toFixed(3)),
    seedLapTime: Number(seed.time.toFixed(3)),
    gain: Number((seed.time - result.time).toFixed(3)),
    minSpeed: { v: Number(minSpeed.v.toFixed(2)), s: Number(minSpeed.s.toFixed(1)) },
    maxSpeed: { v: Number(maxSpeed.v.toFixed(2)), s: Number(maxSpeed.s.toFixed(1)) },
  },
  optimiser: {
    iterations: number('--iterations', 120),
    wallSeconds: Number(elapsed.toFixed(2)),
    first: result.history[0] ?? null,
    last: result.history.at(-1) ?? null,
  },
  corners: corners.slice(0, 14),
  reference: {
    racingLineEstimate: Number(line.estimatedTime().toFixed(3)),
    racingLineOffsetLimit: line.lineLimit,
  },
};

console.log(JSON.stringify(summary, null, 2));

if (!flag('--no-write')) {
  const record = TrackOracle.toJSON(result, {
    track: 'harbor-ring',
    trackLength: track.length,
    legalOffset: oracle.qMax,
    gripScale: envelope.gripScale,
    tyreCore: envelope.tyre.core,
    seedLapTime: Number(seed.time.toFixed(5)),
    optimiserIterations: number('--iterations', 120),
  });
  const jsonPath = resolve(here, '../src/ai/vortex/atlas/oracle-data.json');
  const jsPath = resolve(here, '../src/ai/vortex/atlas/oracle-data.js');
  mkdirSync(dirname(jsonPath), { recursive: true });
  writeFileSync(jsonPath, JSON.stringify(record) + '\n');
  // A generated ES module so both the browser bundle and Node can import the
  // record without relying on JSON import attributes.
  writeFileSync(jsPath, `// Generated by tools/build-vortex-oracle.mjs. Do not edit by hand.\nexport default ${JSON.stringify(record)};\n`);
  console.error(`wrote ${jsonPath}`);
  console.error(`wrote ${jsPath}`);
}

// A stable station probe so tests can assert the atlas stays reproducible.
void sampler;
